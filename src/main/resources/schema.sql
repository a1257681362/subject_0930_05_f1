-- H2 本地文件数据库初始化脚本（每次启动执行，全部使用 IF NOT EXISTS / MERGE 保证幂等）。

-- ---------------------------------------------------------------------------
-- 骨架版本表
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('pf-ledger-1', '植物工厂种植台账：建档/播种/养护/转棚/采收/质检');

-- ---------------------------------------------------------------------------
-- 单据号序列（批次号、采收单号；数据库持久化，重启不重置）
-- ---------------------------------------------------------------------------
CREATE SEQUENCE IF NOT EXISTS seq_pf_batch_no START WITH 1;
CREATE SEQUENCE IF NOT EXISTS seq_pf_harvest_no START WITH 1;

-- ---------------------------------------------------------------------------
-- 操作员（所有业务记录都必须带操作者，1=系统兜底，2=bootstrap 启动账户）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pf_operator (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 3) PRIMARY KEY,
    operator_code VARCHAR(32) NOT NULL,
    operator_name VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_operator_code UNIQUE (operator_code)
);

MERGE INTO pf_operator (id, operator_code, operator_name, status, create_by, create_time)
KEY (id)
VALUES (1, 'SYSTEM', '系统', 'ACTIVE', 1, CURRENT_TIMESTAMP);
MERGE INTO pf_operator (id, operator_code, operator_name, status, create_by, create_time)
KEY (id)
VALUES (2, 'bootstrap', '启动员', 'ACTIVE', 1, CURRENT_TIMESTAMP);
-- 建表时身份列即从 3 开始，显式占用的 1、2 不会与后续自增冲突，且重启不受影响。

-- ---------------------------------------------------------------------------
-- 温室分区：光照 + 营养液循环 + 设备分区
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pf_zone (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_code VARCHAR(32) NOT NULL,
    zone_name VARCHAR(64) NOT NULL,
    zone_role VARCHAR(16) NOT NULL DEFAULT 'GROW',          -- NURSERY 育苗 / GROW 栽培
    lighting_mode VARCHAR(32),                              -- 光照模式，如 LED-全光谱
    daily_light_minutes INT,                                -- 日光照时长（分钟）
    ppfd INT,                                               -- 光照强度 PPFD
    nutrient_mode VARCHAR(32),                              -- 营养液循环模式，如 NFT/DWC
    cycle_interval_min INT,                                 -- 循环间隔（分钟）
    cycle_duration_min INT,                                 -- 每次循环时长（分钟）
    ec_target DECIMAL(5,2),                                 -- 目标 EC
    ph_target DECIMAL(4,2),                                 -- 目标 pH
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_zone_code UNIQUE (zone_code)
);

-- ---------------------------------------------------------------------------
-- 品种
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pf_cultivar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cultivar_code VARCHAR(32) NOT NULL,
    cultivar_name VARCHAR(64) NOT NULL,
    category VARCHAR(32),                                   -- 叶菜/草本/果菜
    default_grow_days INT,                                  -- 默认种植周期（天）
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_cultivar_code UNIQUE (cultivar_code)
);

-- ---------------------------------------------------------------------------
-- 播种盘
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pf_seed_tray (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tray_code VARCHAR(32) NOT NULL,
    tray_name VARCHAR(64) NOT NULL,
    spec VARCHAR(64),                                       -- 规格，如 72 孔穴盘
    capacity INT,
    status VARCHAR(16) NOT NULL DEFAULT 'IDLE',             -- IDLE / IN_USE
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_tray_code UNIQUE (tray_code)
);

-- ---------------------------------------------------------------------------
-- 种植批次：关联品种、播种盘、计划采收日；批次号唯一
-- 状态：DRAFT 建档 → SOWN 播种 → HARVESTED 采收 → QC_PASSED / QC_FAILED 质检
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pf_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no VARCHAR(32) NOT NULL,
    batch_name VARCHAR(64) NOT NULL,
    cultivar_id BIGINT NOT NULL,
    tray_id BIGINT NOT NULL,
    zone_id BIGINT,                                         -- 播种时确定所在分区
    planned_harvest_date DATE,
    seed_qty INT,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    sown_time TIMESTAMP,
    sown_by BIGINT,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_batch_no UNIQUE (batch_no)
);
CREATE INDEX IF NOT EXISTS idx_pf_batch_name ON pf_batch (batch_name);
CREATE INDEX IF NOT EXISTS idx_pf_batch_status ON pf_batch (status);

-- ---------------------------------------------------------------------------
-- 转棚留痕：批次从哪个分区转到哪个分区、谁经办
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pf_zone_transfer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    from_zone_id BIGINT,
    to_zone_id BIGINT NOT NULL,
    reason VARCHAR(220),
    transfer_time TIMESTAMP NOT NULL,
    operator_id BIGINT NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_pf_transfer_batch ON pf_zone_transfer (batch_id);

-- ---------------------------------------------------------------------------
-- 养护记录：光照记录(LIGHT) / 营养液循环记录(NUTRIENT)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pf_care_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    log_type VARCHAR(16) NOT NULL,
    light_minutes INT,
    ppfd INT,
    ec_value DECIMAL(5,2),
    ph_value DECIMAL(4,2),
    volume_ml INT,
    measured_time TIMESTAMP NOT NULL,
    note VARCHAR(255),
    operator_id BIGINT NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_pf_care_batch ON pf_care_log (batch_id);

-- ---------------------------------------------------------------------------
-- 采收单：等级、重量与去向；采收单号唯一
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pf_harvest (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    harvest_no VARCHAR(32) NOT NULL,
    batch_id BIGINT NOT NULL,
    grade VARCHAR(8) NOT NULL,                              -- A/B/C
    gross_weight_kg DECIMAL(10,3) NOT NULL,
    net_weight_kg DECIMAL(10,3),
    destination VARCHAR(64) NOT NULL,                       -- 去向，如 冷库A
    harvest_time TIMESTAMP NOT NULL,
    operator_id BIGINT NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_harvest_no UNIQUE (harvest_no)
);
CREATE INDEX IF NOT EXISTS idx_pf_harvest_batch ON pf_harvest (batch_id);

-- ---------------------------------------------------------------------------
-- 质检单：关联采收单与批次
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pf_qc_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    harvest_id BIGINT NOT NULL,
    result VARCHAR(16) NOT NULL,                            -- PASSED / FAILED
    issues VARCHAR(255),
    qc_time TIMESTAMP NOT NULL,
    inspector_id BIGINT NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_pf_qc_batch ON pf_qc_record (batch_id);
